import { describe, expect, it } from 'vitest';

import generatedFixtureText from '../../generated-fixtures/default/theme.tsx?raw';
import {
  customizedProjectFixture,
  defaultProjectFixture,
} from '../fixtures/theme-project.fixtures';
import { emitThemeTsx } from './emit-theme-tsx';

// Characterization tests: these snapshots pin the exporter's current output
// so the shell rebuild cannot change the generated theme.tsx unnoticed.
// Update them only with a deliberate, reviewed change to the exporter.
describe('emitThemeTsx (characterization)', () => {
  it('pins the output for the default project', () => {
    expect(emitThemeTsx(defaultProjectFixture)).toMatchSnapshot();
  });

  it('pins the output for a customized project', () => {
    expect(emitThemeTsx(customizedProjectFixture)).toMatchSnapshot();
  });

  it('emits the customized values', () => {
    const output = emitThemeTsx(customizedProjectFixture);
    expect(output).toContain("'#6750a4'");
    expect(output).toContain("'#d0bcff'");
    expect(output).toContain('borderRadius: 8');
    expect(output).toContain('spacing: 8');
  });

  it('starts with the generator header and a createTheme call', () => {
    const output = emitThemeTsx(defaultProjectFixture);
    expect(output).toContain('Generated by MUI Theme Builder');
    expect(output).toContain('export const theme = createTheme(');
  });

  // The checked-in generated fixture is a consumer-side compile check
  // (verify:generated); it must be the exporter's actual output for
  // the default project, byte for byte, or the compile check passes
  // on a theme the builder never emits (audit finding C2). Regenerate
  // it from emitThemeTsx(defaultProjectFixture) when the exporter
  // changes deliberately.
  it('the generated fixture matches the exporter output for the default project', () => {
    expect(generatedFixtureText).toBe(emitThemeTsx(defaultProjectFixture));
  });

  it('emits the Phosphor caret import and both dropdown wirings', () => {
    const output = emitThemeTsx(defaultProjectFixture);
    expect(output).toContain("import { CaretDown } from '@phosphor-icons/react';");
    expect(output).toContain('function DropdownIcon(');
    expect(output).toContain('size: 18');
    expect(output).toContain('IconComponent: DropdownIcon');
    expect(output).toContain('popupIcon: createElement(DropdownIcon)');
  });
});
