import type { ThemeOptions } from '@mui/material/styles';

import type { ThemeProject } from '../domain/project';
import {
  DROPDOWN_ICON_SIZE,
  DropdownIcon,
} from '../theme/dropdown-icon';
import { dropdownIconElement } from '../theme/dropdown-icon-element';
import { projectToThemeOptions } from '../theme/project-to-theme-options';
import { emitTypeScriptValue } from './emit-typescript-value';

// The runtime theme options carry two live values that are not plain
// data: the dropdown icon component and its element form (see
// theme/dropdown-icon and theme/dropdown-icon-element). They emit as references to the wrapper defined
// in the preamble below, which the emitted file builds from the
// @phosphor-icons/react package Karl chose for shipped themes (Nov 25,
// 2026) rather than an inline SVG copy of the glyph.
const EMITTED_REFERENCES = new Map<unknown, string>([
  [DropdownIcon, 'DropdownIcon'],
  [dropdownIconElement, 'createElement(DropdownIcon)'],
]);

const DROPDOWN_ICON_PREAMBLE = `import { CaretDown } from '@phosphor-icons/react';
import { createElement, type ComponentProps } from 'react';

// Select and Autocomplete dropdown icon: the Phosphor caret-down at ${DROPDOWN_ICON_SIZE}px.
// The wrapper forwards every prop because MUI Select passes its own
// positioning classes to the icon component.
function DropdownIcon(props: Omit<ComponentProps<typeof CaretDown>, 'size'>) {
  return createElement(CaretDown, { ...props, size: ${DROPDOWN_ICON_SIZE} });
}

`;

function usesDropdownIcon(options: ThemeOptions): boolean {
  const select = options.components?.MuiSelect as
    | { defaultProps?: { IconComponent?: unknown } }
    | undefined;
  const autocomplete = options.components?.MuiAutocomplete as
    | { defaultProps?: { popupIcon?: unknown } }
    | undefined;
  return (
    select?.defaultProps?.IconComponent === DropdownIcon ||
    autocomplete?.defaultProps?.popupIcon === dropdownIconElement
  );
}

export function emitThemeTsx(project: ThemeProject): string {
  const options = projectToThemeOptions(project);
  const preamble = usesDropdownIcon(options) ? DROPDOWN_ICON_PREAMBLE : '';
  return `/**
 * Generated by MUI Theme Builder ${project.builderVersion}.
 * Target: MUI ${project.targetMuiVersion}.
 */
import { createTheme } from '@mui/material/styles';
${preamble}export const theme = createTheme(${emitTypeScriptValue(options, 0, EMITTED_REFERENCES)});
`;
}
